return {
    'nvimdev/dashboard-nvim',
    dependencies = { {'nvim-tree/nvim-web-devicons'}},
    event = 'VimEnter',
    config = function()
        local logo = [[
__/\\\\\_____/\\\_____________________________________________/\\\________/\\\___________________________
 _\/\\\\\\___\/\\\____________________________________________\/\\\_______\/\\\___________________________
  _\/\\\/\\\__\/\\\____________________________________________\//\\\______/\\\___/\\\_____________________
   _\/\\\//\\\_\/\\\_____/\\\\\\\\______/\\\\\_____/\\\\\\\\\\\__\//\\\____/\\\___\///_____/\\\\\__/\\\\\___
    _\/\\\\//\\\\/\\\___/\\\/////\\\___/\\\///\\\__\///////////____\//\\\__/\\\_____/\\\__/\\\///\\\\\///\\\_
     _\/\\\_\//\\\/\\\__/\\\\\\\\\\\___/\\\__\//\\\__________________\//\\\/\\\_____\/\\\_\/\\\_\//\\\__\/\\\_
      _\/\\\__\//\\\\\\_\//\\///////___\//\\\__/\\\____________________\//\\\\\______\/\\\_\/\\\__\/\\\__\/\\\_
       _\/\\\___\//\\\\\__\//\\\\\\\\\\__\///\\\\\/______________________\//\\\_______\/\\\_\/\\\__\/\\\__\/\\\_
        _\///_____\/////____\//////////_____\/////_________________________\///________\///__\///___\///___\///__
  ]]
        logo = string.rep("\n", 8) .. logo .. "\n\n"
        require('dashboard').setup {
            theme = 'doom',
            hide = {
                statusline = false,
            },
            config = {
                header = vim.split(logo, "\n"),
                center = {
                    { action = 'Telescope find_files', desc = " Find File", icon = " ", key = "f" },
                    { action = "edit new", desc = " New File", icon = " ", key = "n" },
                    { action = 'Telescope live_grep', desc = " Find Text", icon = " ", key = "g" },
                    { action = "Lazy", desc = " Lazy", icon = "󰒲 ", key = "l" },
                    { action = function() vim.api.nvim_input("<cmd>qa<cr>") end, desc = " Quit", icon = " ", key = "q" },
                },
            },
        }
    end,
}


